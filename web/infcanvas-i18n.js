  /* Resolve a key to the active language. */
  function translate(key, params) {
    const k = String(key ?? "");
    let out = (lang.value === "en" && Object.prototype.hasOwnProperty.call(EN, k))
      ? EN[k]
      : k;
    if (lang.value === "en" && !Object.prototype.hasOwnProperty.call(EN, k) && /[\u4e00-\u9fff]/.test(k)) {
      if (!warned.has(k)) {
        warned.add(k);
        console.warn("[InfCanvas i18n] missing EN key:", k);
      }
    }
    if (params) {
      for (const name of Object.keys(params)) {
        out = out.split("{" + name + "}").join(String(params[name]));
      }
    }
    return out;
  }
